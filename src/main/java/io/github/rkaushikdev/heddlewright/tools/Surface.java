package io.github.rkaushikdev.heddlewright.tools;

import io.github.rkaushikdev.heddlewright.cli.Commands;
import io.github.rkaushikdev.heddlewright.service.App;
import io.github.rkaushikdev.heddlewright.util.Json;
import io.github.rkaushikdev.heddlewright.util.Table;
import io.github.rkaushikdev.heddlewright.weave.Catalogue;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;

/**
 * The surface document.
 *
 * <p>The routes, the commands and the weave catalogue are written out to a file in {@code docs}, and
 * the same class can check that the file on disk still matches. Nothing is typed into the document by
 * hand, so it cannot drift from the code the way a hand-kept list always does.
 */
public final class Surface {

    /** How the document is regenerated, which the document says at its top. */
    public static final String COMMAND = "java -cp target/classes " + Surface.class.getName();

    /** Whether the document on disk matches the code, and if not why. */
    public record Check(boolean matches, String reason) {}

    private Surface() {}

    /** The document's path. */
    public static Path output() {
        return Sources.root().resolve("docs/surface.md");
    }

    /** The routes the service answers on. */
    public static String routesSection() {
        List<String> lines = new ArrayList<>(List.of("## Routes", ""));
        for (String line : App.routeTable(App.createApp())) {
            lines.add("- `" + line + "`");
        }
        return String.join("\n", lines);
    }

    /** The commands the tool offers. */
    public static String commandsSection() {
        List<Json> rows = Commands.listCommands().stream()
                .map(command -> (Json) Json.obj("command", command.name(), "summary", command.summary()))
                .toList();
        return String.join(
                "\n",
                "## Commands",
                "",
                "```",
                Table.renderTable(rows, List.of(Table.Column.of("command"), Table.Column.of("summary"))),
                "```");
    }

    /** The weave catalogue, measured off the cloth rather than written down. */
    public static String weavesSection() {
        List<Json> rows = Catalogue.measureAll().stream()
                .map(weave -> (Json) Json.obj(
                        "name", weave.name(),
                        "family", weave.family(),
                        "repeat", weave.picks() + "x" + weave.ends(),
                        "warpFace", weave.warpFace(),
                        "float", weave.longestFloat(),
                        "firmness", weave.firmness()))
                .toList();
        List<Table.Column> columns = List.of(
                Table.Column.of("name"),
                Table.Column.of("family"),
                Table.Column.of("repeat"),
                Table.Column.of("warpFace").labelled("warp face"),
                Table.Column.of("float").labelled("longest float"),
                Table.Column.of("firmness"));
        return String.join("\n", "## Weaves", "", "```", Table.renderTable(rows, columns), "```");
    }

    /** The whole document. */
    public static String surface() {
        return String.join(
                "\n",
                "# The heddlewright surface",
                "",
                "This file is generated by `" + COMMAND + "` after a build. Do not edit it by hand.",
                "",
                routesSection(),
                "",
                commandsSection(),
                "",
                weavesSection(),
                "");
    }

    /** Write the document out. */
    public static Path write() {
        try {
            Files.createDirectories(output().getParent());
            Files.writeString(output(), surface(), StandardCharsets.UTF_8);
        } catch (IOException err) {
            throw new UncheckedIOException(err);
        }
        return output();
    }

    /** Whether the document on disk still matches what the code would produce. */
    public static Check check() {
        if (!Files.isRegularFile(output())) {
            return new Check(false, "the surface document has not been written yet");
        }
        if (Sources.read(output()).equals(surface())) {
            return new Check(true, "");
        }
        return new Check(false, "the surface document is out of date, run " + COMMAND);
    }

    /** Write the document, or with {@code --check} say whether it is current and exit non-zero if not. */
    public static void main(String[] args) {
        if (List.of(args).contains("--check")) {
            Check result = check();
            if (!result.matches()) {
                System.err.println(result.reason());
            }
            System.exit(result.matches() ? 0 : 1);
        }
        System.out.println("wrote " + write());
    }
}
