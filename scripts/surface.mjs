import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { createApp } from '../src/service/app.js';
import { routeTable } from '../src/service/app.js';
import { listCommands } from '../src/cli/commands.js';
import { measureAll } from '../src/weave/catalogue.js';
import { renderTable } from '../src/util/table.js';

/**
 * The surface document.
 *
 * The routes, the commands and the weave catalogue are written out to a file in
 * `docs`, and the same function can check that the file on disk still matches.
 * Nothing is typed into the document by hand, so it cannot drift from the code
 * the way a hand-kept list always does.
 */

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUTPUT = join(ROOT, 'docs', 'surface.md');

/** The routes the service answers on. */
export function routesSection() {
  return ['## Routes', '', ...routeTable(createApp()).map((line) => `- \`${line}\``)].join('\n');
}

/** The commands the tool offers. */
export function commandsSection() {
  const rows = listCommands().map((command) => ({
    command: command.name,
    summary: command.summary,
  }));
  return [
    '## Commands',
    '',
    '```',
    renderTable(rows, [{ key: 'command' }, { key: 'summary' }]),
    '```',
  ].join('\n');
}

/** The weave catalogue, measured off the cloth rather than written down. */
export function weavesSection() {
  const rows = measureAll().map((weave) => ({
    name: weave.name,
    family: weave.family,
    repeat: `${weave.picks}x${weave.ends}`,
    warpFace: weave.warpFace,
    float: weave.longestFloat,
    firmness: weave.firmness,
  }));
  const columns = [
    { key: 'name' },
    { key: 'family' },
    { key: 'repeat' },
    { key: 'warpFace', label: 'warp face' },
    { key: 'float', label: 'longest float' },
    { key: 'firmness' },
  ];
  return ['## Weaves', '', '```', renderTable(rows, columns), '```'].join('\n');
}

/** The whole document. */
export function surface() {
  return [
    '# The heddlewright surface',
    '',
    'This file is generated by `npm run surface`. Do not edit it by hand.',
    '',
    routesSection(),
    '',
    commandsSection(),
    '',
    weavesSection(),
    '',
  ].join('\n');
}

/** Write the document out. */
export function write() {
  mkdirSync(join(ROOT, 'docs'), { recursive: true });
  writeFileSync(OUTPUT, surface(), 'utf8');
  return OUTPUT;
}

/** Whether the document on disk still matches what the code would produce. */
export function check() {
  let onDisk;
  try {
    onDisk = readFileSync(OUTPUT, 'utf8');
  } catch {
    return { matches: false, reason: 'the surface document has not been written yet' };
  }
  const wanted = surface();
  if (onDisk === wanted) return { matches: true, reason: '' };
  return { matches: false, reason: 'the surface document is out of date, run npm run surface' };
}

const invoked = process.argv[1] !== undefined && process.argv[1].endsWith('surface.mjs');
if (invoked) {
  if (process.argv.includes('--check')) {
    const result = check();
    if (!result.matches) console.error(result.reason);
    process.exitCode = result.matches ? 0 : 1;
  } else {
    console.log(`wrote ${write()}`);
  }
}
